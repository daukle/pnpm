local OUTPUT = "lock.lua"

local HEADER = "-- Generated by pnpm:resolve. Do not edit: daukle.toml is yours, this is not.\n"
               .. "-- Loaded by daukle itself: no daukle.lua line is needed.\n"

--- A long bracket no line of `text` can close, so the lockfile is carried byte for byte.
local function long_string(text)
  local level = 0
  while string.find(text, "]" .. string.rep("=", level) .. "]", 1, true) ~= nil do
    level = level + 1
  end
  local equals = string.rep("=", level)
  -- A long string drops a newline right after its opening bracket, so one is added to be dropped.
  return "[" .. equals .. "[\n" .. text .. "]" .. equals .. "]"
end

local function quoted_list(values)
  local quoted = {}
  for index = 1, #values do quoted[index] = string.format("%q", values[index]) end
  return "{ " .. table.concat(quoted, ", ") .. " }"
end

--- A text the build compares with its block, as a quoted string.
---
--- @implNote not a long bracket: Lua reads a CRLF inside one as LF, so a value from a CRLF
--- package.json would never equal the pinned one and every build would call the pins stale.
local function exact_string(text)
  return string.format("%q", text)
end

local function ranges_table(list)
  local lines = {}
  for index = 1, #list.names do
    local name = list.names[index]
    lines[index] = string.format("[%q] = %q", name, list.ranges[name])
  end
  return "{ " .. table.concat(lines, ", ") .. " }"
end

local function entry_line(entry)
  local fields = {
    string.format("path = %q", entry.path),
    string.format("url = %q", entry.url),
    string.format("sha256 = %q", entry.sha256),
    string.format("as = %q", entry.name .. " " .. tostring(entry.version)),
  }
  for _, key in ipairs({ "os", "cpu", "libc" }) do
    if entry[key] ~= nil then fields[#fields + 1] = key .. " = " .. quoted_list(entry[key]) end
  end
  return "        { " .. table.concat(fields, ", ") .. " },"
end

--- The key the pin file sets on the pnpm block: the ranges the pins were resolved from, which
--- generate compares with the ranges written now.
local PINNED_FROM = "pinnedFrom"

local function meta_line(spec)
  if spec.peerPackagesMeta == nil then return "" end
  return "      peerPackagesMeta = " .. exact_string(spec.peerPackagesMeta) .. ",\n"
end

local function binary_lines(binaries)
  local hosts = {}
  for host in pairs(binaries) do hosts[#hosts + 1] = host end
  table.sort(hosts)
  for index, host in ipairs(hosts) do
    local binary = binaries[host]
    hosts[index] = string.format("[%q] = { url = %q, sha256 = %q, file = %q }", host, binary.url, binary.sha256,
                                 binary.file)
  end
  return table.concat(hosts, ", ")
end

--- The pinned pnpm as Lua: its one tarball, or a native release's binary per host.
local function pnpm_pin(pnpm)
  if pnpm.binaries ~= nil then
    return string.format("{ version = %q, binaries = { %s } }", pnpm.version, binary_lines(pnpm.binaries))
  end
  return string.format("{ version = %q, url = %q, sha256 = %q }", pnpm.version, pnpm.url, pnpm.sha256)
end

--- The committed pin file: pnpm's lockfile verbatim, the pinned pnpm, and each package's url and
--- sha256, set on the target toolchain, and what they were resolved from, set on the pnpm block.
---
--- @implNote nothing here raises, whatever it finds: core loads this file on every command, so a
--- raise would fail the resolve that rewrites it as well (D-201). Refusing is generate's.
local function render(spec, instance, lock_text, entries)
  local lines = {}
  for index = 1, #entries do lines[index] = entry_line(entries[index]) end
  return HEADER .. "\n"
    .. "do\n"
    .. "  local toolchains = daukle.config.toolchains\n"
    .. string.format("  local own = toolchains and toolchains[%q]\n", instance)
    .. "  if own ~= nil then\n"
    .. "    own." .. PINNED_FROM .. " = {\n"
    .. "      packages = " .. ranges_table(spec.packages) .. ",\n"
    .. "      devPackages = " .. ranges_table(spec.devPackages) .. ",\n"
    .. "      peerPackages = " .. ranges_table(spec.peerPackages) .. ",\n"
    .. "      optionalPackages = " .. ranges_table(spec.optionalPackages) .. ",\n"
    .. meta_line(spec)
    .. string.format("      pnpm = %q,\n", spec.pnpm.version)
    .. (spec.overrides == nil and "" or ("      overrides = " .. exact_string(spec.overrides) .. ",\n"))
    .. "    }\n"
    .. "  end\n"
    .. string.format("  local target = toolchains and toolchains[%q]\n", spec.target)
    .. "  if target ~= nil then\n"
    .. "    target.pnpmLock = {\n"
    .. "      text = " .. long_string(lock_text) .. ",\n"
    .. "      pnpm = " .. pnpm_pin(spec.pnpm) .. ",\n"
    .. "      dependencies = " .. ranges_table(spec.packages) .. ",\n"
    .. "      devDependencies = " .. ranges_table(spec.devPackages) .. ",\n"
    .. (spec.overrides == nil and "" or ("      overrides = " .. exact_string(spec.overrides) .. ",\n"))
    .. "      peerDependencies = " .. ranges_table(spec.peerPackages) .. ",\n"
    .. "      optionalDependencies = " .. ranges_table(spec.optionalPackages) .. ",\n"
    .. meta_line(spec)
    .. "      entries = {\n"
    .. table.concat(lines, "\n") .. (#lines > 0 and "\n" or "")
    .. "      },\n"
    .. "    }\n"
    .. "  end\n"
    .. "end\n"
end

return { OUTPUT = OUTPUT, PINNED_FROM = PINNED_FROM, render = render }
